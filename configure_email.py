#!/usr/bin/env python3
"""
ReliefGrid Email Configuration Tool
Easily configure email settings for password reset functionality
"""

import os
import sys
import getpass

def print_header():
    print("\n" + "="*50)
    print("ReliefGrid Email Configuration Setup")
    print("="*50)
    print("\n⚠️  IMPORTANT: Password reset requires email")
    print("   configuration for security reasons.\n")

def configure_gmail():
    print("\n📧 Gmail Configuration")
    print("-" * 50)
    print("\nBefore proceeding:")
    print("1. Enable 2-Factor Authentication on Gmail")
    print("2. Generate App Password at:")
    print("   https://myaccount.google.com/apppasswords")
    print("3. Select 'Mail' and copy the 16-char password\n")
    
    email = input("Enter your Gmail address: ").strip()
    password = getpass.getpass("Enter Gmail App Password: ").strip()
    
    if not email or not password:
        print("❌ Email and password are required!")
        return False
    
    config = {
        "MAIL_SERVER": "smtp.gmail.com",
        "MAIL_PORT": "587",
        "MAIL_USE_TLS": "True",
        "MAIL_USERNAME": email,
        "MAIL_PASSWORD": password,
        "MAIL_DEFAULT_SENDER": f"ReliefGrid <{email}>"
    }
    
    return config

def configure_custom():
    print("\n📧 Custom SMTP Configuration")
    print("-" * 50)
    
    server = input("SMTP Server: ").strip()
    port = input("SMTP Port (default 587): ").strip() or "587"
    use_tls = input("Use TLS? (y/n, default y): ").strip().lower()
    use_tls = "True" if use_tls != "n" else "False"
    
    username = input("Email Username: ").strip()
    password = getpass.getpass("Email Password: ").strip()
    sender_name = input("Sender Name (default 'ReliefGrid'): ").strip() or "ReliefGrid"
    
    if not server or not username or not password:
        print("❌ Server, username, and password are required!")
        return False
    
    config = {
        "MAIL_SERVER": server,
        "MAIL_PORT": port,
        "MAIL_USE_TLS": use_tls,
        "MAIL_USERNAME": username,
        "MAIL_PASSWORD": password,
        "MAIL_DEFAULT_SENDER": f"{sender_name} <{username}>"
    }
    
    return config

def save_to_env_file(config):
    """Save configuration to .env file"""
    env_file = os.path.join(os.path.dirname(__file__), ".env")
    
    with open(env_file, "w") as f:
        f.write("# ReliefGrid Email Configuration\n")
        f.write("# Generated by configure_email.py\n\n")
        for key, value in config.items():
            f.write(f'{key}="{value}"\n')
    
    print(f"\n✅ Configuration saved to: {env_file}")
    return env_file

def print_summary(config):
    print("\n" + "="*50)
    print("Configuration Summary")
    print("="*50)
    for key, value in config.items():
        if "PASSWORD" in key:
            print(f"{key}: {'*' * 16}")
        else:
            print(f"{key}: {value}")

def print_instructions(env_file):
    print("\n" + "="*50)
    print("Next Steps")
    print("="*50)
    print("\nOption 1: Load from .env file (Recommended)")
    print("-" * 50)
    print("Install python-dotenv:")
    print("  pip install python-dotenv")
    print("\nThen add to app.py (at the top):")
    print("  from dotenv import load_dotenv")
    print("  load_dotenv()")
    print()
    
    print("Option 2: Export as environment variables")
    print("-" * 50)
    print("Linux/Mac:")
    with open(env_file) as f:
        for line in f:
            if line.startswith("MAIL"):
                print(f"  export {line.strip()}")
    print()
    
    print("Option 3: Set before running (temporary)")
    print("-" * 50)
    print("Linux/Mac:")
    print(f"  source {env_file}")
    print("  python app.py")

def main():
    print_header()
    
    # Check if already configured
    if os.getenv("MAIL_USERNAME"):
        print(f"✅ Email already configured: {os.getenv('MAIL_USERNAME')}")
        reconfigure = input("\nReconfigure? (y/n): ").strip().lower()
        if reconfigure != "y":
            print("Keeping existing configuration.")
            return
    
    print("\nChoose email provider:")
    print("1) Gmail (Recommended)")
    print("2) Custom SMTP Server")
    print("0) Exit")
    
    choice = input("\nEnter choice: ").strip()
    
    if choice == "1":
        config = configure_gmail()
    elif choice == "2":
        config = configure_custom()
    elif choice == "0":
        print("Exiting...")
        return
    else:
        print("❌ Invalid choice!")
        return
    
    if not config:
        return
    
    print_summary(config)
    
    save = input("\n💾 Save configuration? (y/n): ").strip().lower()
    if save == "y":
        env_file = save_to_env_file(config)
        print_instructions(env_file)
        
        # Ask to start app
        start = input("\n🚀 Start ReliefGrid now? (y/n): ").strip().lower()
        if start == "y":
            print("\nStarting ReliefGrid...")
            # Set environment variables
            for key, value in config.items():
                os.environ[key] = value
            
            # Import and run app
            try:
                from app import app
                print("\n✅ Email configured successfully!")
                print("🌐 Starting server at http://127.0.0.1:5000\n")
                app.run(debug=True)
            except Exception as e:
                print(f"\n❌ Error starting app: {e}")
                print("Run manually: python app.py")
    else:
        print("\n⚠️  Configuration not saved. Set manually or run again.")

if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n\n⚠️  Configuration cancelled.")
        sys.exit(0)
